           'QHJsLcA2odYIeK4Xqo8O/xUKhI4vI1OU+nYEdL+Z1rI=',
           'SFJNT0RVTEVfU0FMVF8wMg==', 'HR_MANAGER', 1000 FROM DUAL UNION ALL
