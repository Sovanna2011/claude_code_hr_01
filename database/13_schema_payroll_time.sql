/* ============================================================================
   HR Module - Payroll (PY) & Overtime / Public Holidays
   Platform : Oracle Database
   Reference: SAP ECC 6.0 EHP8 - Payroll and Time Management

     HR.PublicHoliday   Holiday calendar (drives OT categorisation)
     HR.OvertimeRecord  Recorded overtime hours per employee/day
     HR.PayrollResult   Payroll run results (RT-style: gross/net per period)
     HR.PayrollConfig   Rates & OT multipliers (customizing)

   Overtime is categorised by date: public holiday > Sunday > normal, each with
   its own pay multiplier - reproduced by the app/report logic.
   ============================================================================ */

BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE HR.PublicHoliday
        (
            HolDate  DATE          NOT NULL,
            HolName  NVARCHAR2(60) NULL,
            MOLGA    VARCHAR2(2)   DEFAULT '01' NOT NULL, -- country grouping
            CONSTRAINT PK_PublicHoliday PRIMARY KEY (MOLGA, HolDate)
        )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

/* OvertimeRecord.Category is a virtual (computed) column. Oracle virtual
   columns must be deterministic, so the weekday test is done with NLS-neutral
   date arithmetic (1970-01-04 was a Sunday) rather than TO_CHAR(...,'DAY').
   Public-holiday overrides Sunday/Normal; the app resolves the final category
   against HR.PublicHoliday (a virtual column cannot join a table). */
BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE HR.OvertimeRecord
        (
            OtId      NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
            PERNR     NUMBER(10)   NOT NULL,
            OtDate    DATE         NOT NULL,
            Hours     NUMBER(6,2)  NOT NULL,
            Category  VARCHAR2(10) GENERATED ALWAYS AS (
                CASE WHEN MOD(TRUNC(OtDate) - DATE '1970-01-04', 7) = 0
                     THEN 'Sunday' ELSE 'Normal' END) VIRTUAL,
            CreatedOn TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_OvertimeRecord PRIMARY KEY (OtId),
            CONSTRAINT FK_Ot_Emp FOREIGN KEY (PERNR) REFERENCES HR.EmployeeMaster(PERNR)
        )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE HR.PayrollConfig
        (
            ConfigKey VARCHAR2(30) NOT NULL,
            NumValue  NUMBER(9,4)  NOT NULL,
            CONSTRAINT PK_PayrollConfig PRIMARY KEY (ConfigKey)
        )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE HR.PayrollResult
        (
            ResultId   NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
            PERNR      NUMBER(10)   NOT NULL,
            PeriodFrom DATE         NOT NULL,
            PeriodTo   DATE         NOT NULL,
            BaseAmount NUMBER(15,2) NOT NULL,
            OtAmount   NUMBER(15,2) DEFAULT 0 NOT NULL,
            Gross      NUMBER(15,2) NOT NULL,
            Tax        NUMBER(15,2) DEFAULT 0 NOT NULL,
            Social     NUMBER(15,2) DEFAULT 0 NOT NULL,
            Net        NUMBER(15,2) NOT NULL,
            Currency   VARCHAR2(5)  DEFAULT 'EUR' NOT NULL,
            RunOn      TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_PayrollResult PRIMARY KEY (ResultId),
            CONSTRAINT FK_PR_Emp FOREIGN KEY (PERNR) REFERENCES HR.EmployeeMaster(PERNR)
        )]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

/* --- Seed ---------------------------------------------------------------- */
MERGE INTO HR.PayrollConfig t
USING (
    SELECT 'TAX_RATE'        ConfigKey, 0.15 NumValue FROM DUAL UNION ALL
    SELECT 'SOCIAL_RATE',               0.09           FROM DUAL UNION ALL
    SELECT 'OT_MULT_NORMAL',            1.25           FROM DUAL UNION ALL
    SELECT 'OT_MULT_SUNDAY',            1.5            FROM DUAL UNION ALL
    SELECT 'OT_MULT_HOLIDAY',           2.0            FROM DUAL UNION ALL
    SELECT 'MONTHLY_FACTOR',            4.33           FROM DUAL
) s ON (t.ConfigKey = s.ConfigKey)
WHEN NOT MATCHED THEN INSERT (ConfigKey, NumValue) VALUES (s.ConfigKey, s.NumValue);

MERGE INTO HR.PublicHoliday t
USING (
    SELECT DATE '2026-01-01' HolDate, 'New Year'            HolName FROM DUAL UNION ALL
    SELECT DATE '2026-04-03',         'Good Friday'                 FROM DUAL UNION ALL
    SELECT DATE '2026-05-01',         'Labour Day'                  FROM DUAL UNION ALL
    SELECT DATE '2026-10-03',         'Day of German Unity'         FROM DUAL UNION ALL
    SELECT DATE '2026-12-25',         'Christmas Day'               FROM DUAL UNION ALL
    SELECT DATE '2026-12-26',         'Boxing Day'                  FROM DUAL
) s ON (t.MOLGA = '01' AND t.HolDate = s.HolDate)
WHEN NOT MATCHED THEN INSERT (HolDate, HolName) VALUES (s.HolDate, s.HolName);

COMMIT;

