-- ============================================================================
--  HR Module - Schema (Oracle Database edition)
--  Reference: SAP ECC 6.0 EHP8 - Human Capital Management (HCM)
--
--  Ported from the SQL Server edition (claude_code_hr_01). Clean-install model:
--  drop and recreate the HR schema/user, then create all objects fresh.
--
--  Run as a privileged user (e.g. SYSTEM) with SQL*Plus / SQLcl:
--      sqlplus system/<pwd>@<service> @run_all.sql
--
--  Oracle notes (differences from SQL Server):
--    * A "schema" is a database user; all objects live in user HR.
--    * Empty string '' equals NULL in Oracle, so SAP "blank" key fields
--      (SUBTY/OBJPS) default to a single space ' ' instead of ''. The .NET
--      InfotypeBase mirrors this (defaults to " ").
--    * INT->NUMBER(10), BIGINT->NUMBER(19), NVARCHAR->NVARCHAR2,
--      DECIMAL->NUMBER, BIT->NUMBER(1), DATETIME2->TIMESTAMP, TIME->INTERVAL.
--    * IDENTITY -> GENERATED BY DEFAULT ON NULL AS IDENTITY.
-- ============================================================================

-- ---- Schema / user ---------------------------------------------------------
BEGIN
   EXECUTE IMMEDIATE 'DROP USER HR CASCADE';
EXCEPTION WHEN OTHERS THEN
   IF SQLCODE != -1918 THEN RAISE; END IF;   -- ORA-01918: user does not exist
END;
/

CREATE USER HR IDENTIFIED BY hr
   DEFAULT TABLESPACE USERS
   QUOTA UNLIMITED ON USERS;
GRANT CONNECT, RESOURCE, CREATE VIEW TO HR;

ALTER SESSION SET CURRENT_SCHEMA = HR;

